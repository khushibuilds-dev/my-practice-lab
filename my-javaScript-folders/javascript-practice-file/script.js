// inverse Camel Case
function inverseCamelCase(camlecase){
    let result = ""
    for(let char of camlecase){
        if(char >= "A" && char <= "Z"){
        result += " " + char.toLowerCase();
        } else{
            result += char;
        }
    }
    return result;
}
