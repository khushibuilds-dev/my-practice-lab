function countUniqueVowels(word){
    let lowerStr = word.toLowerCase();
    let uniquesBox = new Set();
    for(let vowel of lowerStr){
        if(vowel === "a" || vowel === "e" || vowel === "i" || vowel === "o" || vowel === "u" ){
            uniquesBox.add(vowel);
        }
    }
    return uniquesBox.size;
}
console.log(countUniqueVowels("Khushi has gone"));

// togggle chacter

function toggleCharcter(data){
    let result = "";
    for(let char of data){
        if(char >= "a" && char <= "z"){
            result += char.toUpperCase();
        }
        else if(char >= "A" && char <= "Z"){
            result += char.toLowerCase();
        } else {
            result += char
        }
    }
    return result;
}
